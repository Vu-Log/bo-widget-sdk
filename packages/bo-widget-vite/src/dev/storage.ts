/**
 * The data storage of the fake back office (`bo.storage`, `bo.sharedStorage`): two spaces in
 * memory, with the checks of the back office (the request) and of the Vulog server (versions,
 * expiry, pages, queries, quotas). Lost when the page reloads.
 *
 * Runs in the browser, like `host.ts`.
 *
 * @packageDocumentation
 */
import type { BoStorageOp, BoStorageSpace } from '@vulog/bo-widget-sdk';
import { WidgetHostError, invalidPayload } from './hostError.js';

/** Operations of a storage request, one per method of a collection. */
export const STORAGE_OPS: readonly BoStorageOp[] = [
  'get',
  'set',
  'add',
  'update',
  'delete',
  'list',
  'query',
  'clear',
];

/** Name of a collection. */
const COLLECTION_PATTERN = /^[a-z0-9][a-z0-9_-]{0,63}$/;
/** Id of a document: `__x__` is reserved. */
const DOC_ID_PATTERN = /^(?!__.*__$)[A-Za-z0-9_-]{1,128}$/;
/** Largest value, in bytes of its UTF-8 JSON form. */
export const STORAGE_VALUE_MAX_BYTES = 64 * 1024;
/** Deepest value: the value object itself is depth 1. */
const VALUE_MAX_DEPTH = 20;
/** Longest field path (`data.<key>.<key>…`), in UTF-8 bytes, each key with a `.` and two backquotes. */
const FIELD_PATH_MAX_BYTES = 1500;
const ROOT_PATH_BYTES = 'data'.length;
const RESERVED_KEY = /^__.*__$/;
const VALUE_TOO_LARGE = `value is larger than ${STORAGE_VALUE_MAX_BYTES} bytes`;
const NOT_JSON =
  'value can only hold strings, finite numbers, booleans, null, arrays and plain objects';
const TTL_MIN_SECONDS = 60;
const TTL_MAX_SECONDS = 365 * 24 * 60 * 60;
const LIST_DEFAULT_LIMIT = 50;
const LIST_MAX_LIMIT = 100;
const WHERE_MAX_FIELDS = 5;
const WHERE_FIELD_PATTERN = /^(?!__.*__$)[A-Za-z_][A-Za-z0-9_]{0,63}$/;
const WHERE_STRING_MAX_BYTES = 1500;
const CURSOR_MAX_LENGTH = 1024;
/** Characters of an id generated by `add`, as the server generates them. */
const GENERATED_ID_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const GENERATED_ID_LENGTH = 20;

/** Quotas of a space, with the defaults of the server. */
export interface StorageQuotas {
  collectionsPerSpace: number;
  docsPerCollection: number;
  bytesPerSpace: number;
}

export const DEFAULT_STORAGE_QUOTAS: Readonly<StorageQuotas> = Object.freeze({
  collectionsPerSpace: 20,
  docsPerCollection: 10_000,
  bytesPerSpace: 50 * 1024 * 1024,
});

/** Fields a request may hold; any other defined field is refused. */
const REQUEST_KEYS = new Set(['op', 'collection', 'id', 'value', 'options']);

type OptionName = 'ifVersion' | 'ttlSeconds' | 'limit' | 'cursor' | 'where';

/** What each operation takes: an `id`, a `value`, and which options (`required` ones must be given). */
const OP_SHAPES: Record<
  BoStorageOp,
  { id: boolean; value: boolean; options: OptionName[]; required?: OptionName[] }
> = {
  get: { id: true, value: false, options: [] },
  set: { id: true, value: true, options: ['ifVersion', 'ttlSeconds'] },
  add: { id: false, value: true, options: ['ttlSeconds'] },
  update: { id: true, value: true, options: ['ifVersion', 'ttlSeconds'] },
  delete: { id: true, value: false, options: [] },
  list: { id: false, value: false, options: ['limit', 'cursor'] },
  query: { id: false, value: false, options: ['where', 'limit', 'cursor'], required: ['where'] },
  clear: { id: false, value: false, options: [] },
};

type JsonObject = Record<string, unknown>;

/** A storage request, checked by {@link parseStorageRequest}. */
export interface StorageRequest {
  op: BoStorageOp;
  collection: string;
  id?: string;
  /** A JSON copy of the value the widget passed. */
  value?: JsonObject;
  options: {
    ifVersion?: number;
    ttlSeconds?: number | null;
    limit?: number;
    cursor?: string;
    where?: Record<string, string | number | boolean | null>;
  };
}

const utf8Bytes = (text: string): number => new TextEncoder().encode(text).length;

const isPlainObject = (value: unknown): value is JsonObject => {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  const proto: unknown = Object.getPrototypeOf(value);
  return proto === Object.prototype || proto === null;
};

/**
 * Why a JSON value nested at `depth` cannot be stored, as the back office checks it. Stops past the
 * depth limit, and past {@link STORAGE_VALUE_MAX_BYTES} visited nodes (each one takes a byte at
 * least in JSON), so that a cyclic or shared value cannot freeze the page.
 */
const findValueIssue = (
  value: unknown,
  depth: number,
  insideArray: boolean,
  pathBytes: number,
  visited: { nodes: number },
): string | null => {
  visited.nodes += typeof value === 'string' ? Math.max(value.length, 1) : 1;
  if (visited.nodes > STORAGE_VALUE_MAX_BYTES) return VALUE_TOO_LARGE;
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return null;
  if (typeof value === 'number') return Number.isFinite(value) ? null : 'a number must be finite';
  if (depth > VALUE_MAX_DEPTH) return `value is nested deeper than ${VALUE_MAX_DEPTH} levels`;
  if (Array.isArray(value)) {
    if (insideArray) return 'value cannot hold an array directly inside an array';
    for (const item of value as unknown[]) {
      const issue = findValueIssue(item, depth + 1, true, pathBytes, visited);
      if (issue) return issue;
    }
    return null;
  }
  if (!isPlainObject(value)) return NOT_JSON;
  const entries = Object.entries(value);
  visited.nodes += entries.length;
  if (visited.nodes > STORAGE_VALUE_MAX_BYTES) return VALUE_TOO_LARGE;
  for (const [key, child] of entries) {
    if (key === '__proto__') return 'value cannot hold a __proto__ key';
    if (RESERVED_KEY.test(key)) return 'value cannot hold a key that starts and ends with "__"';
    const childPathBytes = pathBytes + 1 + utf8Bytes(key) + 2;
    if (key === '' || childPathBytes > FIELD_PATH_MAX_BYTES) {
      return `value cannot hold an empty key, nor a key path longer than ${FIELD_PATH_MAX_BYTES} bytes`;
    }
    if (child !== undefined) {
      const issue = findValueIssue(child, depth + 1, false, childPathBytes, visited);
      if (issue) return issue;
    }
  }
  return null;
};

/**
 * A JSON copy of a value, or why it is refused. Copied first (`structuredClone`, which refuses
 * functions), then the copy is checked and kept: the widget cannot change it afterwards.
 */
const parseValue = (value: unknown): { value: JsonObject } | { issue: string } => {
  if (!isPlainObject(value)) {
    return { issue: 'value must be a JSON object (store a scalar as { value: 42 })' };
  }
  let copy: unknown;
  try {
    copy = structuredClone(value);
  } catch {
    return { issue: NOT_JSON };
  }
  const issue = findValueIssue(copy, 1, false, ROOT_PATH_BYTES, { nodes: 0 });
  if (issue) return { issue };
  const json = JSON.stringify(copy);
  if (utf8Bytes(json) > STORAGE_VALUE_MAX_BYTES) return { issue: VALUE_TOO_LARGE };
  return { value: JSON.parse(json) as JsonObject };
};

const checkWhere = (where: unknown): string | null => {
  if (!isPlainObject(where)) return 'options.where must be an object { field: value }';
  const entries = Object.entries(where);
  if (entries.length === 0 || entries.length > WHERE_MAX_FIELDS) {
    return `options.where must hold 1 to ${WHERE_MAX_FIELDS} fields`;
  }
  const invalid = entries.find(([field, value]) => {
    if (!WHERE_FIELD_PATTERN.test(field)) return true;
    if (typeof value === 'string') return utf8Bytes(value) > WHERE_STRING_MAX_BYTES;
    return !(value === null || typeof value === 'boolean' || Number.isFinite(value));
  });
  return invalid
    ? `options.where.${invalid[0].slice(0, 64)}: the field must be a first-level name, and its value a ` +
        `string of ${WHERE_STRING_MAX_BYTES} bytes at most, a finite number, a boolean or null`
    : null;
};

const isSafeInteger = (value: unknown): value is number => Number.isSafeInteger(value);

const OPTION_CHECKS: Record<OptionName, (value: unknown) => string | null> = {
  ifVersion: (value) =>
    isSafeInteger(value) && value >= 0 ? null : 'options.ifVersion must be an integer >= 0',
  ttlSeconds: (value) =>
    value === null || (isSafeInteger(value) && value >= TTL_MIN_SECONDS && value <= TTL_MAX_SECONDS)
      ? null
      : `options.ttlSeconds must be an integer from ${TTL_MIN_SECONDS} to ${TTL_MAX_SECONDS}, or null`,
  limit: (value) =>
    isSafeInteger(value) && value >= 1 && value <= LIST_MAX_LIMIT
      ? null
      : `options.limit must be an integer from 1 to ${LIST_MAX_LIMIT}`,
  cursor: (value) =>
    typeof value === 'string' && value && value.length <= CURSOR_MAX_LENGTH
      ? null
      : 'options.cursor must be the nextCursor of the previous page',
  where: checkWhere,
};

const parseOptions = (
  op: BoStorageOp,
  options: unknown,
): { options: StorageRequest['options'] } | { issue: string } => {
  const shape = OP_SHAPES[op];
  if (options === undefined || options === null) {
    return shape.required ? { issue: `options.${shape.required[0]} is required` } : { options: {} };
  }
  if (!isPlainObject(options)) return { issue: 'options must be an object' };
  const set = Object.entries(options).filter(([, value]) => value !== undefined);
  const unknown = set.find(([name]) => !shape.options.includes(name as OptionName));
  if (unknown) {
    const accepted = shape.options.length ? shape.options.join(', ') : 'none';
    return { issue: `unknown option '${unknown[0].slice(0, 64)}' (accepted: ${accepted})` };
  }
  const missing = (shape.required ?? []).find((name) => options[name] === undefined);
  if (missing) return { issue: `options.${missing} is required` };
  const issue = set.map(([name, value]) => OPTION_CHECKS[name as OptionName](value)).find(Boolean);
  if (issue) return { issue };
  return { options: Object.fromEntries(set) as StorageRequest['options'] };
};

/**
 * Checks a storage request `{ op, collection, id?, value?, options? }` as the back office does,
 * in the same order: not an object, unknown `op`, unknown field, `collection`, `id` (missing,
 * invalid, or given to an operation without id), `value` (missing, not storable or larger than
 * 64 KB, or given to an operation without value), `options` (not an object, unknown, required
 * `where` missing, invalid value).
 *
 * @param payload - The request, from the port or built by `vulogBo.storage`.
 * @param space - Named in the message.
 * @returns The request, its value copied as JSON.
 * @throws {WidgetHostError} `invalid-payload` with what is wrong.
 */
export const parseStorageRequest = (payload: unknown, space: BoStorageSpace): StorageRequest => {
  if (!isPlainObject(payload)) {
    throw invalidPayload(`${space}: the request must be an object { op, collection, … }`);
  }
  const { op, collection, id, value } = payload;
  if (!STORAGE_OPS.includes(op as BoStorageOp)) {
    throw invalidPayload(`${space}: op must be one of ${STORAGE_OPS.join(', ')}`);
  }
  const storageOp = op as BoStorageOp;
  const refuse = (issue: string) => invalidPayload(`${space}.${storageOp}: ${issue}`);
  const unknownKey = Object.keys(payload).find(
    (key) => !REQUEST_KEYS.has(key) && payload[key] !== undefined,
  );
  if (unknownKey) throw refuse(`unknown field '${unknownKey.slice(0, 64)}' in the request`);
  if (typeof collection !== 'string' || !COLLECTION_PATTERN.test(collection)) {
    throw refuse(`collection must match ${COLLECTION_PATTERN}`);
  }
  const shape = OP_SHAPES[storageOp];
  if (shape.id && (typeof id !== 'string' || !DOC_ID_PATTERN.test(id))) {
    throw refuse('id must be 1 to 128 letters, digits, _ or -, not starting and ending with __');
  }
  if (!shape.id && id !== undefined) throw refuse('this operation takes no id');
  let parsedValue: JsonObject | undefined;
  if (shape.value) {
    const parsed = parseValue(value);
    if ('issue' in parsed) throw refuse(parsed.issue);
    parsedValue = parsed.value;
  } else if (value !== undefined) {
    throw refuse('this operation takes no value');
  }
  const parsedOptions = parseOptions(storageOp, payload.options);
  if ('issue' in parsedOptions) throw refuse(parsedOptions.issue);
  return {
    op: storageOp,
    collection,
    ...(shape.id ? { id: id as string } : {}),
    ...(parsedValue ? { value: parsedValue } : {}),
    options: parsedOptions.options,
  };
};

/** A stored document. Dates in ms since the epoch. */
interface StoredDocument {
  value: JsonObject;
  /** Bytes of `value` as UTF-8 JSON. */
  size: number;
  version: number;
  createdAt: number;
  createdBy: string;
  updatedAt: number;
  updatedBy: string;
  expiresAt?: number;
}

/** A document as the server answers it. */
export interface StorageDocument {
  id: string;
  value: JsonObject;
  version: number;
  createdAt: string;
  createdBy: string;
  updatedAt: string;
  updatedBy: string;
  expiresAt?: string;
}

/** Options of {@link createFakeStorage}. */
export interface FakeStorageOptions {
  /** `createdBy` / `updatedBy` of the writes: the id of the fake user. */
  userId: string;
  /** The clock, in ms since the epoch. `Date.now` by default. */
  now?: () => number;
  /** Generates the id of `add`. 20 random letters and digits by default. */
  generateId?: () => string;
  quotas?: Partial<StorageQuotas>;
}

const randomId = (): string => {
  const bytes = crypto.getRandomValues(new Uint8Array(GENERATED_ID_LENGTH));
  return Array.from(
    bytes,
    (byte) => GENERATED_ID_ALPHABET[byte % GENERATED_ID_ALPHABET.length],
  ).join('');
};

/** The cursor of the page after `id`: the id in base64url, as the server makes it. */
const encodeCursor = (id: string): string =>
  btoa(id).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');

/** The id a cursor stands for, only for a cursor {@link encodeCursor} makes. */
const decodeCursor = (cursor: string): string | undefined => {
  if (!/^[A-Za-z0-9_-]+$/.test(cursor)) return undefined;
  let id: string;
  try {
    id = atob(cursor.replace(/-/g, '+').replace(/_/g, '/'));
  } catch {
    return undefined;
  }
  return DOC_ID_PATTERN.test(id) && encodeCursor(id) === cursor ? id : undefined;
};

const serverError = (
  code: ConstructorParameters<typeof WidgetHostError>[0],
  status: number,
  message: string,
): WidgetHostError => new WidgetHostError(code, message, status);

/**
 * Creates the in-memory storage of the fake back office: the widget's space (`storage`) and its
 * publisher's shared space (`sharedStorage`), apart from each other. It answers like the server:
 *
 * - `get` of a missing or expired document: `not-found` (404);
 * - `set` creates or replaces; `update` merges the first-level fields and needs the document
 *   (`not-found`); `ifVersion: 0` refuses an existing document (`already-exists`, 409), another
 *   `ifVersion` a different version (`version-conflict`, 409);
 * - `ttlSeconds` sets the expiry from now, `null` removes it; without it, `set` and `add` write a
 *   document that does not expire and `update` keeps the expiry. An expired document is absent;
 * - `list` and `query` answer pages in id order, `nextCursor` the base64url id of the last
 *   document; a cursor it did not make is `invalid-cursor` (400);
 * - a merged value over 64 KB is `value-too-large` (413); a write past a quota (collections per
 *   space, documents per collection, bytes per space) is `quota-exceeded` (422);
 * - `delete` answers `null`, even for a missing document; `clear` answers `{ deletedDocs }`.
 *
 * No rate limit. Every answer is a copy: the widget cannot change what is stored.
 */
export const createFakeStorage = (options: FakeStorageOptions) => {
  const now = options.now ?? Date.now;
  const generateId = options.generateId ?? randomId;
  const quotas: StorageQuotas = { ...DEFAULT_STORAGE_QUOTAS, ...options.quotas };
  /** Space → collection → id → document. */
  const spaces: Record<BoStorageSpace, Map<string, Map<string, StoredDocument>>> = {
    storage: new Map(),
    sharedStorage: new Map(),
  };

  const isLive = (stored: StoredDocument | undefined, at: number): stored is StoredDocument =>
    stored !== undefined && (stored.expiresAt === undefined || stored.expiresAt > at);

  /** Deletes the expired documents of a space, as the server eventually does. */
  const purge = (space: BoStorageSpace, at: number): void => {
    for (const docs of spaces[space].values()) {
      for (const [id, stored] of docs) if (!isLive(stored, at)) docs.delete(id);
    }
  };

  const toDocument = (id: string, stored: StoredDocument): StorageDocument => ({
    id,
    value: structuredClone(stored.value),
    version: stored.version,
    createdAt: new Date(stored.createdAt).toISOString(),
    createdBy: stored.createdBy,
    updatedAt: new Date(stored.updatedAt).toISOString(),
    updatedBy: stored.updatedBy,
    ...(stored.expiresAt === undefined
      ? {}
      : { expiresAt: new Date(stored.expiresAt).toISOString() }),
  });

  const checkQuotas = (
    space: BoStorageSpace,
    collection: string,
    createsDocument: boolean,
    bytesDelta: number,
  ): void => {
    const collections = spaces[space];
    const docs = collections.get(collection);
    if (!docs && collections.size >= quotas.collectionsPerSpace) {
      throw serverError(
        'quota-exceeded',
        422,
        `${space}: ${quotas.collectionsPerSpace} collections at most`,
      );
    }
    if (createsDocument && (docs?.size ?? 0) >= quotas.docsPerCollection) {
      throw serverError(
        'quota-exceeded',
        422,
        `${space}: ${quotas.docsPerCollection} documents per collection at most`,
      );
    }
    if (bytesDelta <= 0) return;
    let used = 0;
    for (const collectionDocs of collections.values()) {
      for (const stored of collectionDocs.values()) used += stored.size;
    }
    if (used + bytesDelta > quotas.bytesPerSpace) {
      throw serverError('quota-exceeded', 422, `${space}: ${quotas.bytesPerSpace} bytes at most`);
    }
  };

  const write = (space: BoStorageSpace, request: StorageRequest, id: string, at: number) => {
    const { op, collection, options: writeOptions } = request;
    const docs = spaces[space].get(collection);
    const live = docs?.get(id);
    if (op === 'update' && !live)
      throw serverError('not-found', 404, `${space}.update: no document ${id}`);
    const { ifVersion, ttlSeconds } = writeOptions;
    if (ifVersion === 0 && live) {
      throw serverError('already-exists', 409, `${space}.${op}: the document ${id} exists`);
    }
    if (ifVersion !== undefined && ifVersion !== 0 && ifVersion !== (live?.version ?? 0)) {
      throw serverError(
        'version-conflict',
        409,
        `${space}.${op}: the document ${id} is not at version ${ifVersion}`,
      );
    }
    const value =
      op === 'update' && live ? { ...live.value, ...request.value } : (request.value as JsonObject);
    const size = utf8Bytes(JSON.stringify(value));
    if (size > STORAGE_VALUE_MAX_BYTES) {
      throw serverError('value-too-large', 413, `${space}.${op}: ${VALUE_TOO_LARGE}`);
    }
    checkQuotas(space, collection, !live, size - (live?.size ?? 0));
    const expiresAt =
      ttlSeconds === undefined
        ? op === 'update'
          ? live?.expiresAt
          : undefined
        : ttlSeconds === null
          ? undefined
          : at + ttlSeconds * 1000;
    const stored: StoredDocument = {
      value,
      size,
      version: live ? live.version + 1 : 1,
      createdAt: live?.createdAt ?? at,
      createdBy: live?.createdBy ?? options.userId,
      updatedAt: at,
      updatedBy: options.userId,
      ...(expiresAt === undefined ? {} : { expiresAt }),
    };
    if (docs) docs.set(id, stored);
    else spaces[space].set(collection, new Map([[id, stored]]));
    return toDocument(id, stored);
  };

  const page = (space: BoStorageSpace, { collection, options: pageOptions }: StorageRequest) => {
    const after = pageOptions.cursor === undefined ? undefined : decodeCursor(pageOptions.cursor);
    if (pageOptions.cursor !== undefined && after === undefined) {
      throw serverError(
        'invalid-cursor',
        400,
        `${space}: the cursor must be a nextCursor answered by a list`,
      );
    }
    const limit = pageOptions.limit ?? LIST_DEFAULT_LIMIT;
    const where = Object.entries(pageOptions.where ?? {});
    const matching = [...(spaces[space].get(collection) ?? [])]
      .filter(([id]) => after === undefined || id > after)
      .filter(([, stored]) =>
        where.every(
          ([field, expected]) =>
            Object.hasOwn(stored.value, field) && stored.value[field] === expected,
        ),
      )
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    const items = matching.slice(0, limit);
    const last = items.at(-1);
    return {
      items: items.map(([id, stored]) => toDocument(id, stored)),
      nextCursor: matching.length > limit && last ? encodeCursor(last[0]) : null,
    };
  };

  return {
    /**
     * Runs a storage request on a space.
     *
     * @param space - `storage` or `sharedStorage`.
     * @param payload - `{ op, collection, id?, value?, options? }`.
     * @returns What the server answers: a document, a page, `{ deletedDocs }` or `null`.
     * @throws {WidgetHostError} `invalid-payload` for a request the back office refuses, or the
     * code and status of the server.
     */
    run(space: BoStorageSpace, payload: unknown): unknown {
      const request = parseStorageRequest(payload, space);
      const at = now();
      purge(space, at);
      const { op, collection, id } = request;
      const docs = spaces[space].get(collection);
      switch (op) {
        case 'get': {
          const stored = docs?.get(id as string);
          if (!stored) throw serverError('not-found', 404, `${space}.get: no document ${id}`);
          return toDocument(id as string, stored);
        }
        case 'set':
        case 'update':
          return write(space, request, id as string, at);
        case 'add':
          return write(space, request, generateId(), at);
        case 'delete':
          docs?.delete(id as string);
          return null;
        case 'list':
        case 'query':
          return page(space, request);
        case 'clear':
          spaces[space].delete(collection);
          return { deletedDocs: docs?.size ?? 0 };
      }
    },
    /**
     * Empties both spaces.
     *
     * @returns The number of documents deleted, expired ones included.
     */
    clear(): number {
      let deleted = 0;
      for (const space of Object.values(spaces)) {
        for (const docs of space.values()) deleted += docs.size;
        space.clear();
      }
      return deleted;
    },
  };
};

/** The storage of the fake back office. */
export type FakeStorage = ReturnType<typeof createFakeStorage>;
